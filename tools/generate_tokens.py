#!/usr/bin/env python3
"""Generate native immutable tokens from the checked-in upstream snapshot."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "tokens/fluent2.json").read_text())
MODES = DATA["modes"]
FIRST = MODES["light"]
COLORS = list(FIRST["colors"])
NUMBERS = list(FIRST["dimensions"])
NOTICE = "Generated by tools/generate_tokens.py from Fluent 2 " + DATA["version"] + ". DO NOT EDIT."


def number(value):
    return str(float(value))


def kotlin():
    lines = [f"// {NOTICE}", "// Upstream MIT license: THIRD_PARTY_NOTICES.md", "package dev.fluent2.core", "",
             "import androidx.compose.runtime.Immutable", "import androidx.compose.ui.graphics.Color", "",
             "@Immutable", "data class FluentColors("]
    lines += [f"    val {key}: Color," for key in COLORS]
    lines += [")", "", "@Immutable", "data class FluentMetrics("]
    lines += [f"    val {key}: Float," for key in NUMBERS]
    lines += [")", "", "@Immutable", "data class FluentTokens(val isDark: Boolean, val colors: FluentColors, val metrics: FluentMetrics) {"]
    lines += [f"    val {key}: Color get() = colors.{key}" for key in COLORS]
    lines += [f"    val {key}: Float get() = metrics.{key}" for key in NUMBERS]
    lines += ["", "    companion object {"]
    for mode, data in MODES.items():
        lines += [f"        val {mode} = FluentTokens(", f"            isDark = {str(data['isDark']).lower()},", "            colors = FluentColors("]
        lines += [f"                {key} = Color(0x{data['colors'][key][1:]})," for key in COLORS]
        lines += ["            ),", "            metrics = FluentMetrics("]
        lines += [f"                {key} = {number(data['dimensions'][key])}f," for key in NUMBERS]
        lines += ["            ),", "        )"]
    return "\n".join(lines + ["    }", "}", ""])


def dart():
    lines = [f"// {NOTICE}", "// Upstream MIT license: THIRD_PARTY_NOTICES.md",
             "import 'package:flutter/foundation.dart';", "import 'package:flutter/painting.dart';", "",
             "@immutable", "class FluentTokens {", "  const FluentTokens({", "    required this.isDark,"]
    lines += [f"    required this.{key}," for key in COLORS + NUMBERS]
    lines += ["  });", "", "  final bool isDark;"]
    lines += [f"  final Color {key};" for key in COLORS]
    lines += [f"  final double {key};" for key in NUMBERS]
    lines += ["", "  FluentTokens copyWith({", "    bool? isDark,"]
    lines += [f"    Color? {key}," for key in COLORS]
    lines += [f"    double? {key}," for key in NUMBERS]
    lines += ["  }) => FluentTokens(", "    isDark: isDark ?? this.isDark,"]
    lines += [f"    {key}: {key} ?? this.{key}," for key in COLORS + NUMBERS]
    lines += ["  );", ""]
    for mode, data in MODES.items():
        lines += [f"  static const {mode} = FluentTokens(", f"    isDark: {str(data['isDark']).lower()},"]
        lines += [f"    {key}: Color(0x{data['colors'][key][1:]})," for key in COLORS]
        lines += [f"    {key}: {number(data['dimensions'][key])}," for key in NUMBERS]
        lines += ["  );", ""]
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        "packages/compose/src/commonMain/kotlin/dev/fluent2/core/FluentTokens.kt": kotlin(),
        "packages/flutter/lib/src/theme/fluent_tokens.dart": dart(),
    }
    for relative, content in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated file out of date: {relative}. Run python3 tools/generate_tokens.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"{'Verified' if args.check else 'Generated'} {len(COLORS)} colors and {len(NUMBERS)} dimensions in 4 modes for both libraries.")


if __name__ == "__main__":
    main()
